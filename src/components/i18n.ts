export const LOCALES: Record<Lang, { num: string; date: string }> = {
  tr: { num: 'tr-TR', date: 'tr-TR' },
  en: { num: 'en-US', date: 'en-GB' },
}

export function getStoredLang(): Lang {
  try {
    const v = localStorage.getItem('lang')
    if (v === 'tr' || v === 'en') return v
  } catch {}
  return 'tr'
}

